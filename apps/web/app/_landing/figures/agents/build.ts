/* ------------------------------------------------------------------------------------------------ audit */

type Poses = Array<{ name: string; pose: Pose; level: number }>;

/** Proves every pose, and that the keys settled at rest still order every overlapping pair in the others. */
function audit(name: string, poses: Poses, make: (pose: Pose, level: number) => Scene, P: typeof TP) {
  const restKeys = new Map<string, number>();
  poses.forEach(({ name: label, pose, level }, index) => {
    const scene = make(pose, level);
    console.log(`\n== ${name} pose ${label}: ${scene.parts.length} parts`);
    A.settle(scene.R, P);
    if (index === 0) for (const item of scene.R.items) restKeys.set(item.name, item.key);
    A.auditOrExit(scene.R, P, { argv: [...argv, "--audit"] });
    if (index > 0) {
      // The painter's order is fixed at rest: lay those keys over this pose and count the pairs they draw the wrong way round.
      for (const item of scene.R.items) item.key = restKeys.get(item.name) ?? item.key;
      const depth = A.depthOrder(scene.R.items, P) as { problems: unknown[] };
      console.log(`rest keys in this pose: ${depth.problems.length} depth-order problems`);
      if (depth.problems.length) process.exitCode = 1;
    }
  });
}

