// A day's segment is the last run + 1 points; its mean is what the agent compares with the threshold.
const dayOf = (point: RawPoint): Day => {
  const segment = volatile.points.slice(Math.max(0, point.idx - 1 - point.mapR), point.idx);
  return { idx: point.idx, price: point.pricePhp, cp: point.cpRecent, run: point.mapR, mean: segment.reduce((sum, item) => sum + item.pricePhp, 0) / segment.length };
};
const all = volatile.points.map(dayOf);
