// Geometry audit for the dispenser figure, with the kit's own audit (iso/audit.mjs).
//   pnpm --filter server exec tsx ../web/app/_landing/figures/dispenser/audit.ts --audit        prove it
//   ... --write                                                                                  settle the painter's keys into order.gen.ts
// It also checks that the model's price path is the real "staircase" scenario of scenarios.json.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as A from "../../iso/audit.mjs";
import type { Part } from "./build";
import { GATE_LIFT, NOTCH_DEG } from "./kin";
import { DAY_NO, DAY_PRICE, type Copy } from "./model";
import { buildScene } from "./scene";
import { MAX_DEG } from "./kin";
import { P } from "./view";

const here = dirname(fileURLToPath(import.meta.url));
const argv = process.argv;
const stub: Copy = { money: Array.from({ length: 46 }, (_, index) => `₱${index * 100}`), price: DAY_PRICE.map((price) => price.toFixed(2)), mark: "65.00", lgu: "LGU" };

const scenarios = JSON.parse(readFileSync(join(here, "../../scenarios.json"), "utf8")) as { scenarios: Array<{ id: string; fireIdx: number; points: Array<{ idx: number; pricePhp: number }> }> };
const staircase = scenarios.scenarios.find((scenario) => scenario.id === "staircase");
if (!staircase) throw new Error("scenario staircase is gone");
const drift = DAY_NO.map((idx, index) => [idx, staircase.points.find((point) => point.idx === idx)?.pricePhp, DAY_PRICE[index]] as const).filter(([, real, mine]) => real !== mine);
if (drift.length || staircase.fireIdx !== DAY_NO[DAY_NO.length - 1]) throw new Error(`model price path drifted from scenarios.json: ${JSON.stringify(drift)} fire ${staircase.fireIdx}`);
console.log(`prices: days ${DAY_NO.join(", ")} match scenarios.json (staircase, fires on day ${staircase.fireIdx})`);

const poses = [
  { name: "rest", lever: NOTCH_DEG[0]!, latch: 0, gate: 0 },
  { name: "held", lever: NOTCH_DEG[4]!, latch: 0, gate: 0 },
  { name: "run", lever: (NOTCH_DEG[4]! + MAX_DEG) / 2, latch: 24, gate: GATE_LIFT / 2 },
  { name: "released", lever: MAX_DEG, latch: 48, gate: GATE_LIFT },
];

for (const pose of poses) {
  const scene = buildScene(stub, pose, pose.name === "rest" ? undefined : []);
  const R = scene.R;
  console.log(`\n== pose ${pose.name}: lever ${pose.lever}°, latch ${pose.latch}° · ${scene.parts.length} parts`);
  if (pose.name === "rest") {
    A.settle(R, P);
    const keys: Record<string, number> = {};
    for (const item of R.items) keys[item.name] = Math.round(item.key * 1000) / 1000;
    if (argv.includes("--write")) {
      const rows = scene.parts.map((part: Part) => `  ${JSON.stringify(part.id)}: ${keys[part.id]},`).join("\n");
      writeFileSync(join(here, "order.gen.ts"), `// Generated by audit.ts --write: painter's keys settled from the recorded shapes. Do not edit.\nexport const ORDER: Record<string, number> = {\n${rows}\n};\n`);
      console.log(`wrote order.gen.ts (${scene.parts.length} keys)`);
    }
    A.auditOrExit(R, P, { argv: [...argv, "--audit"] });
  } else {
    // Posed runs: the lever, weight, pin and latch at their true places; nothing else moves, so the explode replay is off.
    const flat = buildScene(stub, pose, []);
    A.settle(flat.R, P, { states: [0] });
    A.auditOrExit(flat.R, P, { argv: [...argv, "--audit"] });
  }
}
